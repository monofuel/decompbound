proc readFlavorDescriptors(rom: openArray[uint8]): array[FlavorDescriptorCount,
    FlavorDescriptor] =
  ## Decode the five structural flavor records and verify their known shape.
  for index in 0 ..< FlavorDescriptorCount:
    let offset = FlavorDescriptorFile + index * FlavorDescriptorStride
    result[index] = FlavorDescriptor(
      paletteOffset: rom[offset].int or (rom[offset + 1].int shl 8),
      subtype: rom[offset + 2].int)
    doAssert result[index].paletteOffset == ExpectedPaletteOffsets[index]
    doAssert result[index].subtype == ExpectedSubtypes[index]

proc verifyOriginalDecompress(rom: seq[uint8], source: uint32,
    decoded: openArray[uint8]) =
  ## Compare direct decoding with the original `$C41A9E` output byte for byte.
  let machine = newSnesBus(rom)
  defer:
    machine.bus.readHook = nil
    machine.bus.writeHook = nil
  machine.put16(0x0E, int(source and 0xFFFF))
  machine.put16(0x10, int(source shr 16))
  machine.put16(0x12, OracleDestination)
  machine.put16(0x14, 0x007F)
  for index in 0 ..< decoded.len:
    machine.bus.write8(0x7F0000'u32 + OracleDestination.uint32 + index.uint32,
      OracleSentinel)
  discard machine.callOriginal(OriginalDecompress, 0)
  for index, expected in decoded:
    let actual = machine.bus.read8(
      0x7F0000'u32 + OracleDestination.uint32 + index.uint32)
    doAssert actual == expected,
      &"Original decompressor mismatch for ${source:06X} at decoded +0x{index:X}"

proc expectedPaletteByte(rom: openArray[uint8], sourceFile, index: int): uint8 =
  ## Model the loader's transparent-color clear after its 64-byte copy.
  if index < TransparentPaletteBytes:
    result = 0
  else:
    result = rom[sourceFile + index]

proc preparePaletteOracle(machine: SnesBus, selector, condition, guard: int) =
  ## Install generated WRAM inputs that choose a controlled palette branch.
  machine.put8(FlavorSelectorWram, selector)
  machine.put8(PartyCountWram, 1)
  machine.put8(PartyRosterWram, 0)
  machine.put16(PartyRecordIndexWram, PartyRecordTest)
  machine.put8(PartyRecordTest + PartyConditionOffset, condition)
  machine.put16(PaletteOverrideGuardWram, guard)

proc verifyPaletteCopy(rom: seq[uint8], selector, condition, guard,
    sourceFile: int) =
  ## Execute `$C47F87` and compare its complete WRAM staging palette.
  let machine = newSnesBus(rom)
  defer:
    machine.bus.readHook = nil
    machine.bus.writeHook = nil
  machine.preparePaletteOracle(selector, condition, guard)
  discard machine.callOriginal(OriginalFlavorPaletteLoader)
  for index in 0 ..< FlavorPaletteBytes:
    let expected = rom.expectedPaletteByte(sourceFile, index)
    doAssert machine.get8(PaletteStageWram + index) == expected,
      &"Flavor {selector} palette mismatch at staging +0x{index:X}"

proc verifyTileContract(rom: openArray[uint8], common, overlay: DecodedStream,
    descriptors: array[FlavorDescriptorCount, FlavorDescriptor]) =
  ## Verify direct-decoder ranges needed by native status and flavor UI.
  doAssert common.data.len == CommonChrDecodedSize
  doAssert common.consumed == CommonChrCompressedSize
  doAssert FlavorOverlayDestination + overlay.data.len <= common.data.len
  for tileId in BorderTileIds:
    doAssert tileId < EarlyTileCount
    doAssert (tileId + 1) * BytesPer2BppTile <= common.data.len
  for index in 0 ..< HpPpLabelCount:
    let tileId = rom[HpPpLabelFile + index].int
    doAssert tileId < EarlyTileCount,
      &"HP/PP label tile ${tileId:02X} is outside the first UI upload"
  let digitBytes = (DigitTileLast - DigitTileFirst + 1) * BytesPer2BppTile
  doAssert DigitDecodedOffset + digitBytes == common.data.len
  for descriptor in descriptors:
    let sourceFile = FlavorPaletteBaseFile + descriptor.paletteOffset
    doAssert sourceFile >= FlavorPaletteBaseFile
    doAssert sourceFile + FlavorPaletteBytes <= FlavorSpecialFile

proc verifyOriginalUiBuild(rom: seq[uint8], assets: EbUiAssets, flavor: int) =
  ## Compare generated status-icon tiles and complete names to the original loader.
  let
    machine = newSnesBus(rom)
    colors: array[4, ColorRGBA] = [ColorRGBA(a: 255),
      ColorRGBA(r: 255, a: 255), ColorRGBA(g: 255, a: 255), ColorRGBA(b: 255, a: 255)]
  defer:
    machine.bus.readHook = nil
    machine.bus.writeHook = nil
  machine.put8(FlavorSelectorWram, flavor)
  for member in 0 .. 3:
    for index in 0 .. member:
      machine.put8(0x99CE + member * 0x5F + index, 0x71 + index)
  discard machine.callOriginal(CommonUiLoader)
  for index, byte in assets.statusIcons:
    doAssert machine.bus.read8(0x7F2C00'u32 + index.uint32) == byte,
      "Original generated status-icon byte mismatch at " & $index
  for member in 0 .. 3:
    let image = newImage(32, 16)
    var encoded: seq[uint8]
    for index in 0 .. member: encoded.add(uint8(0x71 + index))
    for y in 0 .. 15:
      for x in 0 .. 31:
        image[x, y] = colors[assets.uiTilePixel(7, x mod 8, y mod 8, flavor)]
    image.drawEbText(assets.fonts[2], encoded, 2, 0,
      [ColorRGBA(), colors[1], colors[2], colors[3]], maxWidth = 30)
    for y in 0 .. 15:
      for x in 0 .. 31:
        let
          address = 0x7F2A00'u32 + uint32(member * 64 + (y div 8) * 256 +
            (x div 8) * 16 + (y mod 8) * 2)
          plane0 = machine.bus.read8(address)
          plane1 = machine.bus.read8(address + 1)
          pixel = int((plane0 shr (7 - x mod 8)) and 1) or
            (int((plane1 shr (7 - x mod 8)) and 1) shl 1)
        doAssert image[x, y] == colors[pixel].rgbx,
          "Original status name pixel mismatch at " & $x & "," & $y

proc main() =
  ## Verify original loaders and the assets actually used by the native UI.
  let
    rom = readGoldBaserom()
    assets = loadEbUiAssets(rom)
    common = rom.decodeStream(CommonChrFile)
    overlay = rom.decodeStream(FlavorOverlayFile)
    descriptors = rom.readFlavorDescriptors()
  rom.verifyLoaderInstructions()
  rom.verifyOriginalDecompress(CommonChrSnes, assets.graphics.tiles)
  rom.verifyOriginalDecompress(FlavorOverlaySnes, assets.flavorOverlay)
  rom.verifyTileContract(common, overlay, descriptors)
  for index, descriptor in descriptors:
    let
      base = FlavorPaletteBaseFile + descriptor.paletteOffset
      colors = assets.uiColors(index + 1, false)
    rom.verifyPaletteCopy(index + 1, 0, 1, base)
    for color in 0 ..< colors.len:
      let word = if color == 0: 0'u16
        else: rom[base + color * 2].uint16 or (rom[base + color * 2 + 1].uint16 shl 8)
      doAssert colors[color] == bgr555ToColor(word)
    for tile in BorderTileIds:
      for y in 0 .. 7:
        for x in 0 .. 7:
          let
            offset = tile * BytesPer2BppTile + y * 2
            pixel = int((common.data[offset] shr (7 - x)) and 1) or
              (int((common.data[offset + 1] shr (7 - x)) and 1) shl 1)
          doAssert assets.uiTilePixel(tile, x, y, index + 1) == pixel
    for tile in 0x10 .. 0x16:
      for y in 0 .. 7:
        for x in 0 .. 7:
          let
            offset = if index == 0: tile * 16 + y * 2 else: (tile - 0x10) * 16 + y * 2
            bytes = if index == 0: common.data else: overlay.data
            pixel = int((bytes[offset] shr (7 - x)) and 1) or
              (int((bytes[offset + 1] shr (7 - x)) and 1) shl 1)
          doAssert assets.uiTilePixel(tile, x, y, index + 1) == pixel
    for tile in DigitTileFirst .. DigitTileLast:
      for y in 0 .. 7:
        for x in 0 .. 7:
          let
            offset = DigitDecodedOffset + (tile - DigitTileFirst) * 16 + y * 2
            pixel = int((common.data[offset] shr (7 - x)) and 1) or
              (int((common.data[offset + 1] shr (7 - x)) and 1) shl 1)
          doAssert assets.uiTilePixel(tile, x, y, index + 1) == pixel
  for tile in [4, 0x10, 0x200, 0x2C0]:
    doAssert assets.uiTilePixel(tile, -1, 0, 2) == 0
    doAssert assets.uiTilePixel(tile, 0, 8, 2) == 0
  rom.verifyPaletteCopy(FlavorDescriptorCount, 1, 0, FlavorSpecialFile)
  rom.verifyOriginalUiBuild(assets, 1)
  rom.verifyOriginalUiBuild(assets, 2)

main()
