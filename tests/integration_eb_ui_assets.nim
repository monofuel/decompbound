## Verify the original common UI CHR and flavor-palette loader contracts.
##
## Read the user's ROM and compare native assets with isolated original routines.

import
  std/[strformat, strutils],
  pixie,
  decompbound/[asm_parse, assembler, cpu, disasm, eb_ui_assets, eb_ui_font, gfx_lz, opcodes,
    ppu, rom_pipeline, snesbus]

type
  FlavorDescriptor = object
    ## Describe one three-byte flavor record without retaining palette bytes.
    paletteOffset: int
    subtype: int

  DecodedStream = object
    ## Hold one locally decoded stream and its compressed extent.
    data: seq[uint8]
    consumed: int

const
  Wram = 0x7E0000'u32
  Caller = 0x1E00'u32
  DirectPage = 0x1A00'u16
  StackTop = 0x1FFF'u16
  StepLimit = 1_000_000
  CommonChrFile = 0x200000
  CommonChrSnes = 0xE00000'u32
  CommonChrDecodedSize = 0x1A00
  CommonChrCompressedSize = 0x0754
  FlavorOverlayFile = 0x200754
  FlavorOverlaySnes = 0xE00754'u32
  FlavorOverlayDestination = 0x0100
  FlavorDescriptorFile = 0x201FB9
  FlavorDescriptorSnes = 0xE01FB9'u32
  FlavorDescriptorCount = 5
  FlavorDescriptorStride = 3
  FlavorPaletteBaseFile = 0x201FC8
  FlavorPaletteBaseSnes = 0xE01FC8'u32
  FlavorPaletteBytes = 0x40
  DynamicPalettePatchBytes = 0x08
  FlavorSpecialFile = 0x202108
  FlavorSpecialSnes = 0xE02108'u32
  FlavorSelectorWram = 0x99CD
  FlavorFirst = 1
  FlavorLast = 5
  PaletteStageWram = 0x0200
  TransparentPaletteBytes = 2
  PartyCountWram = 0x98A4
  PartyRosterWram = 0x9891
  PartyRecordIndexWram = 0x4DC8
  PartyRecordTest = 0x3000
  PartyConditionOffset = 0x0E
  PaletteOverrideGuardWram = 0xB4B6
  OriginalDecompress = 0xC41A9E'u32
  OriginalFlavorPaletteLoader = 0xC47F87'u32
  OriginalBackwardCopy = 0xC08EED'u32
  OriginalFarCopy = 0xC08ED2'u32
  OriginalVramUpload = 0xC08616'u32
  OriginalCgramRequest = 0xC0856B'u32
  CommonUiLoader = 0xC47C3F'u32
  UiChrPublisher = 0xC44963'u32
  OracleDestination = 0x4000
  OracleSentinel = 0xA5'u8
  BorderTileIds = [4, 5, 6]
  EarlyTileCount = 0x45
  DigitTileFirst = 0x200
  DigitTileLast = 0x29F
  BytesPer2BppTile = 16
  DigitDecodedOffset = 0x1000
  HpPpLabelFile = 0x03E3F8
  HpPpLabelCount = 8
  ExpectedPaletteOffsets = [0x0000, 0x0040, 0x0080, 0x00C0, 0x0100]
  ExpectedSubtypes = [1, 8, 8, 8, 8]

proc put8(machine: SnesBus, address: int, value: int) =
  ## Write one generated byte to WRAM.
  machine.bus.write8(Wram + address.uint32, uint8(value and 0xFF))

proc put16(machine: SnesBus, address: int, value: int) =
  ## Write one generated little-endian word to WRAM.
  machine.put8(address, value)
  machine.put8(address + 1, value shr 8)

proc get8(machine: SnesBus, address: int): uint8 =
  ## Read one byte from WRAM.
  machine.bus.read8(Wram + address.uint32)

proc callOriginal(machine: SnesBus, target: uint32, directPage = DirectPage): Cpu =
  ## Invoke one original RTL routine through an isolated WRAM trampoline.
  let code = assembleAsm(".a16\n.i16\nJSL $" & target.toHex(6) & "\n", Caller)
  for index, value in code:
    machine.bus.write8(Wram + Caller + index.uint32, value)
  var
    state = Cpu(pbr: 0x7E, pc: Caller.uint16, s: StackTop, d: directPage,
      dbr: 0x7E)
    steps = 0
  while state.pbr != 0x7E or state.pc != (Caller + code.len.uint32).uint16:
    doAssert steps < StepLimit,
      &"Original ${target:06X} did not return at {state.pbr:02X}:{state.pc:04X}"
    state.step(machine.bus)
    inc steps
  doAssert state.s == StackTop
  result = state

proc decodeStream(rom: openArray[uint8], fileOffset: int): DecodedStream =
  ## Decode one terminated graphics stream and require a clean terminator.
  let decoded = decodeWithConsumed(rom.toOpenArray(fileOffset, rom.high))
  doAssert decoded.clean, &"Unterminated graphics stream at 0x{fileOffset:06X}"
  result = DecodedStream(data: decoded.data, consumed: decoded.consumed)

proc expectInstruction(rom: openArray[uint8], fileOffset: int,
    expectedMnemonic: string, expectedOperand: uint32) =
  ## Require one semantic instruction at an evidence address.
  let instruction = decode(rom, fileOffset, NativeFlags16)
  doAssert instruction.mnemonic == expectedMnemonic,
    &"0x{fileOffset:06X}: got {instruction.mnemonic}, want {expectedMnemonic}"
  doAssert instruction.operand == expectedOperand,
    &"0x{fileOffset:06X}: {expectedMnemonic} operand " &
    &"${instruction.operand:X}, want ${expectedOperand:X}"

proc verifyLoaderInstructions(rom: openArray[uint8]) =
  ## Verify the address-by-address loader, relocation, upload, and selector chain.
  # TODO: Promote these verified routine contracts into named assembly when this
  # UI subsystem is adopted; the probe keeps the evidence semantic in the meantime.
  rom.expectInstruction(0x047C47, "LDA", 0x0000)
  rom.expectInstruction(0x047C4C, "LDA", 0x00E0)
  rom.expectInstruction(0x047C51, "LDA", 0x0000)
  rom.expectInstruction(0x047C56, "LDA", 0x007F)
  rom.expectInstruction(0x047C5B, "JSL", OriginalDecompress)
  rom.expectInstruction(0x047C5F, "LDA", 0x2000)
  rom.expectInstruction(0x047C69, "LDA", 0x1000)
  rom.expectInstruction(0x047C73, "LDA", 0x2A00)
  rom.expectInstruction(0x047C76, "JSL", OriginalBackwardCopy)
  rom.expectInstruction(0x047C8F, "LDA", FlavorSelectorWram.uint32)
  rom.expectInstruction(0x047C9E, "LDA", FlavorDescriptorSnes)
  rom.expectInstruction(0x047CA5, "CMP", 0x0008)
  rom.expectInstruction(0x047CAA, "LDA", FlavorOverlaySnes and 0xFFFF)
  rom.expectInstruction(0x047CAF, "LDA", FlavorOverlaySnes shr 16)
  rom.expectInstruction(0x047CB4, "LDA", FlavorOverlayDestination)
  rom.expectInstruction(0x047CB9, "LDA", 0x007F)
  rom.expectInstruction(0x047CBE, "JSL", OriginalDecompress)

  rom.expectInstruction(0x044982, "LDA", 0x2000)
  rom.expectInstruction(0x044987, "LDA", 0x007F)
  rom.expectInstruction(0x04498C, "LDY", 0x7000)
  rom.expectInstruction(0x04498F, "LDX", 0x1800)
  rom.expectInstruction(0x044996, "JSL", OriginalVramUpload)
  rom.expectInstruction(0x04499A, "LDA", 0x0000)
  rom.expectInstruction(0x04499F, "LDA", 0x007F)
  rom.expectInstruction(0x0449A4, "LDY", 0x6000)
  rom.expectInstruction(0x0449A7, "LDX", 0x0450)
  rom.expectInstruction(0x0449AE, "JSL", OriginalVramUpload)

  rom.expectInstruction(0x047FD9, "LDA", FlavorSelectorWram.uint32)
  rom.expectInstruction(0x047FE6, "LDA", FlavorDescriptorSnes)
  rom.expectInstruction(0x047FCF, "LDA", FlavorPaletteBaseSnes and 0xFFFF)
  rom.expectInstruction(0x047FD4, "LDA", FlavorPaletteBaseSnes shr 16)
  rom.expectInstruction(0x047FF5, "LDX", FlavorPaletteBytes)
  rom.expectInstruction(0x047FF8, "LDA", PaletteStageWram)
  rom.expectInstruction(0x047FFB, "JSL", OriginalFarCopy)
  rom.expectInstruction(0x047FFF, "STZ", PaletteStageWram)
  rom.expectInstruction(0x048002, "LDA", 0x0008)
  rom.expectInstruction(0x048005, "JSL", OriginalCgramRequest)

  rom.expectInstruction(0x04801E, "JSL", CommonUiLoader)
  rom.expectInstruction(0x048022, "LDA", 0x0002)
  rom.expectInstruction(0x048025, "JSL", UiChrPublisher)
  rom.expectInstruction(0x048029, "JSL", OriginalFlavorPaletteLoader)
  rom.expectInstruction(0x01F796, "LDX", FlavorSelectorWram.uint32)
  rom.expectInstruction(0x01F79F, "BNE", 0x0007)

  rom.expectInstruction(0x03E4B5, "LDX", DynamicPalettePatchBytes)
  rom.expectInstruction(0x03E4B8, "LDA", 0x0228)
  rom.expectInstruction(0x03E4BB, "JSL", OriginalFarCopy)
  rom.expectInstruction(0x019D2E, "LDX", DynamicPalettePatchBytes)
